'use strict'

// Extracts the piece-tree text buffer from a VS Code repository, compiles it
// to CommonJS, and vendors the result into vendor/vscode-piecetree/. This is
// how the JS TextBuffer's storage backend (src/js/piece-tree-text.js) tracks
// the actively-maintained implementation inside microsoft/vscode.
//
// Usage:
//   node script/update-vendored-piece-tree.js                # clone microsoft/vscode HEAD
//   node script/update-vendored-piece-tree.js --repo /path/to/vscode
//   node script/update-vendored-piece-tree.js --repo https://github.com/microsoft/vscode.git --ref <sha|branch|tag>
//
// What it does:
//   1. Obtains a VS Code working tree (local path, or shallow+sparse clone).
//   2. Copies the piece-tree core and its small leaf dependencies, preserving
//      the vs/ directory layout so relative imports keep working.
//   3. Generates stub modules for the two "hub" imports (vs/editor/common/
//      model.ts and .../model/textModelSearch.ts). The piece tree only uses
//      them for its built-in find methods, which superstring does not call
//      (superstring has its own regex search) — the stubs throw if reached.
//   4. Verifies the import closure: every import of every copied file must
//      resolve to another copied file or a stub. If upstream grows a new
//      dependency, the script fails with the list instead of silently
//      producing a broken build.
//   5. Compiles with the local TypeScript (devDependency) to CommonJS and
//      writes vendor/vscode-piecetree/ with an index.js barrel, VS Code's
//      MIT license, and a metadata file recording the source commit.
//
// After running, `npm run test:node` must pass — the adapter test suite
// (test/js/piece-tree-text.test.js) differentially fuzzes the vendored build
// against a reference model and is the gate for accepting an upstream update.

const fs = require('fs')
const path = require('path')
const os = require('os')
const {execFileSync} = require('child_process')

const ROOT = path.join(__dirname, '..')
const VENDOR_DIR = path.join(ROOT, 'vendor', 'vscode-piecetree')
const DEFAULT_REPO = 'https://github.com/microsoft/vscode.git'

// Real source files to vendor, relative to <vscode>/src/. The piece-tree
// core plus its leaf dependencies (position/range/charCode import nothing
// beyond each other).
const SOURCE_FILES = [
  'vs/editor/common/model/pieceTreeTextBuffer/pieceTreeBase.ts',
  'vs/editor/common/model/pieceTreeTextBuffer/rbTreeBase.ts',
  'vs/editor/common/core/position.ts',
  'vs/editor/common/core/range.ts',
  'vs/base/common/charCode.ts'
]

// Hub modules replaced by stubs (paths relative to <vscode>/src/). Only the
// symbols the piece tree actually references are declared.
const STUB_FILES = {
  'vs/editor/common/model.ts': `/*---------------------------------------------------------------------------
 * Stub generated by script/update-vendored-piece-tree.js. The real
 * vs/editor/common/model.ts is a hub module that would drag in most of the
 * editor. The piece tree only needs these symbols; FindMatch/SearchData are
 * only reached through the built-in find methods, which superstring never
 * calls (it implements its own search on top of the raw text).
 *--------------------------------------------------------------------------*/

export interface ITextSnapshot {
\tread(): string | null;
}

export class FindMatch {
\t_findMatchBrand: void = undefined;
\tpublic readonly range: any;
\tpublic readonly matches: string[] | null;
\tconstructor(range: any, matches: string[] | null) {
\t\tthis.range = range;
\t\tthis.matches = matches;
\t}
}

export class SearchData {
\tpublic readonly regex: RegExp;
\tpublic readonly wordSeparators: any;
\tpublic readonly simpleSearch: string | null;
\tconstructor(regex: RegExp, wordSeparators: any, simpleSearch: string | null) {
\t\tthis.regex = regex;
\t\tthis.wordSeparators = wordSeparators;
\t\tthis.simpleSearch = simpleSearch;
\t}
}
`,
  'vs/editor/common/model/textModelSearch.ts': `/*---------------------------------------------------------------------------
 * Stub generated by script/update-vendored-piece-tree.js. The real
 * textModelSearch.ts depends on the full TextModel. These symbols are only
 * used by PieceTreeBase.findMatchesInNode/findMatchesLineByLine, which the
 * superstring adapter never calls — reaching a stub is a programming error.
 *--------------------------------------------------------------------------*/

const NOT_SUPPORTED = 'vendored piece tree: built-in search is not included; use superstring\\'s own search';

export class Searcher {
\tpublic _wordSeparators: any;
\tconstructor(_wordSeparators: any, _searchRegex: RegExp) {
\t\tthrow new Error(NOT_SUPPORTED);
\t}
\tpublic reset(_lastIndex: number): void {
\t\tthrow new Error(NOT_SUPPORTED);
\t}
\tpublic next(_text: string): RegExpExecArray | null {
\t\tthrow new Error(NOT_SUPPORTED);
\t}
}

export function createFindMatch(_range: any, _rawMatches: RegExpExecArray, _captureMatches: boolean): any {
\tthrow new Error(NOT_SUPPORTED);
}

export function isValidMatch(_wordSeparators: any, _text: string, _textLength: number, _matchStartIndex: number, _matchLength: number): boolean {
\tthrow new Error(NOT_SUPPORTED);
}
`
}

function parseArgs (argv) {
  const args = {repo: null, ref: null}
  for (let i = 2; i < argv.length; i++) {
    if (argv[i] === '--repo') args.repo = argv[++i]
    else if (argv[i] === '--ref') args.ref = argv[++i]
    else if (argv[i] === '--help' || argv[i] === '-h') {
      console.log('Usage: node script/update-vendored-piece-tree.js [--repo <path-or-git-url>] [--ref <sha|branch|tag>]')
      process.exit(0)
    } else {
      console.error(`Unknown argument: ${argv[i]}`)
      process.exit(1)
    }
  }
  return args
}

function run (cmd, args, opts) {
  const options = Object.assign({encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit']}, opts)
  return execFileSync(cmd, args, options).trim()
}

// Returns {srcRoot, commit, source, cleanup}
function obtainVSCodeCheckout ({repo, ref}) {
  const isLocalPath = repo && !/^(https?|git|ssh):/.test(repo) && !repo.endsWith('.git')
  if (isLocalPath) {
    const localRoot = path.resolve(repo)
    if (!fs.existsSync(path.join(localRoot, 'src', 'vs'))) {
      throw new Error(`${localRoot} does not look like a VS Code checkout (no src/vs directory)`)
    }
    let commit = 'unknown'
    try { commit = run('git', ['-C', localRoot, 'rev-parse', 'HEAD']) } catch (e) {}
    return {srcRoot: path.join(localRoot, 'src'), commit, source: localRoot, cleanup: () => {}}
  }

  const url = repo || DEFAULT_REPO
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'vscode-piecetree-'))
  console.log(`Cloning ${url}${ref ? ` @ ${ref}` : ''} (sparse, shallow) ...`)
  run('git', ['clone', '--depth', '1', '--filter=blob:none', '--sparse',
    ...(ref ? ['--branch', ref] : []), url, tmp])
  run('git', ['-C', tmp, 'sparse-checkout', 'set',
    'src/vs/editor/common', 'src/vs/base/common'])
  const commit = run('git', ['-C', tmp, 'rev-parse', 'HEAD'])
  return {
    srcRoot: path.join(tmp, 'src'),
    commit,
    source: url,
    cleanup: () => fs.rmSync(tmp, {recursive: true, force: true})
  }
}

// Extract the module specifiers of all static imports in a TS source.
function importsOf (source) {
  const specifiers = []
  const re = /^import\s[^'"]*['"]([^'"]+)['"]/gm
  let m
  while ((m = re.exec(source)) !== null) specifiers.push(m[1])
  return specifiers
}

// Every import of every vendored real file must resolve (following the
// relative specifier, .js -> .ts) to another vendored file or a stub.
function verifyClosure (staging) {
  const known = new Set([...SOURCE_FILES, ...Object.keys(STUB_FILES)])
  const problems = []
  for (const file of SOURCE_FILES) {
    const source = fs.readFileSync(path.join(staging, file), 'utf8')
    for (const spec of importsOf(source)) {
      if (!spec.startsWith('.')) {
        problems.push(`${file}: non-relative import '${spec}'`)
        continue
      }
      const resolved = path.posix
        .join(path.posix.dirname(file), spec)
        .replace(/\.js$/, '.ts')
      if (!known.has(resolved)) {
        problems.push(`${file}: import '${spec}' -> ${resolved} is not vendored or stubbed`)
      }
    }
  }
  if (problems.length > 0) {
    throw new Error(
      'The upstream import closure changed; update SOURCE_FILES or STUB_FILES in this script:\n  ' +
      problems.join('\n  '))
  }
}

function compile (staging, outDir) {
  let tsc
  try {
    const tsPackage = require.resolve('typescript/package.json', {paths: [ROOT]})
    tsc = path.join(path.dirname(tsPackage), 'bin', 'tsc')
  } catch (e) {
    throw new Error("TypeScript not found — run 'npm install' first (it is a devDependency)")
  }
  const tsconfig = {
    compilerOptions: {
      module: 'node16',          // CommonJS emit (no "type": "module" here),
      target: 'ES2022',          // and .js import specifiers resolve to .ts
      lib: ['ES2024'],
      strict: false,
      declaration: false,
      sourceMap: false,
      skipLibCheck: true,
      types: [],
      newLine: 'lf',
      rootDir: '.',
      outDir: path.relative(staging, outDir) || '.'
    },
    include: ['vs/**/*.ts']
  }
  fs.writeFileSync(path.join(staging, 'tsconfig.json'), JSON.stringify(tsconfig, null, 2))
  execFileSync(process.execPath, [tsc, '-p', staging], {stdio: 'inherit'})
}

function smokeTest (vendorDir) {
  // Re-require a fresh copy even if something loaded it earlier.
  for (const key of Object.keys(require.cache)) {
    if (key.startsWith(vendorDir)) delete require.cache[key]
  }
  const {PieceTreeBase, Position, Range} = require(vendorDir)
  const tree = new PieceTreeBase([], '\n', false)
  tree.insert(0, 'hello\r\nworld', false)
  tree.delete(0, 1)
  const assert = require('assert')
  assert.strictEqual(tree.getLinesRawContent(), 'ello\r\nworld')
  assert.strictEqual(tree.getLineCount(), 2)
  assert.strictEqual(tree.getLineContent(2), 'world')
  assert.strictEqual(tree.getOffsetAt(2, 1), 6)
  const pos = tree.getPositionAt(7)
  assert.strictEqual(pos.lineNumber, 2)
  assert.strictEqual(pos.column, 2)
  assert.strictEqual(tree.getValueInRange(new Range(1, 1, 2, 1)), 'ello\r\n')
  assert.ok(new Position(1, 1))
}

function main () {
  const args = parseArgs(process.argv)
  const checkout = obtainVSCodeCheckout(args)
  const staging = fs.mkdtempSync(path.join(os.tmpdir(), 'piecetree-staging-'))
  try {
    for (const file of SOURCE_FILES) {
      const from = path.join(checkout.srcRoot, file)
      if (!fs.existsSync(from)) {
        throw new Error(`Expected source file missing from VS Code checkout: src/${file}\n` +
          'Upstream may have moved it; update SOURCE_FILES in this script.')
      }
      const to = path.join(staging, file)
      fs.mkdirSync(path.dirname(to), {recursive: true})
      fs.copyFileSync(from, to)
    }
    for (const [file, contents] of Object.entries(STUB_FILES)) {
      const to = path.join(staging, file)
      fs.mkdirSync(path.dirname(to), {recursive: true})
      fs.writeFileSync(to, contents)
    }

    verifyClosure(staging)

    fs.rmSync(VENDOR_DIR, {recursive: true, force: true})
    fs.mkdirSync(VENDOR_DIR, {recursive: true})
    console.log('Compiling with TypeScript ...')
    compile(staging, VENDOR_DIR)

    // Barrel with the API surface src/js/piece-tree-text.js consumes.
    fs.writeFileSync(path.join(VENDOR_DIR, 'index.js'),
`'use strict'
// Generated by script/update-vendored-piece-tree.js — do not edit.
const pieceTreeBase = require('./vs/editor/common/model/pieceTreeTextBuffer/pieceTreeBase.js')
const position = require('./vs/editor/common/core/position.js')
const range = require('./vs/editor/common/core/range.js')
module.exports = {
  PieceTreeBase: pieceTreeBase.PieceTreeBase,
  StringBuffer: pieceTreeBase.StringBuffer,
  createLineStartsFast: pieceTreeBase.createLineStartsFast,
  Position: position.Position,
  Range: range.Range
}
`)

    const license = fs.readFileSync(path.join(checkout.srcRoot, '..', 'LICENSE.txt'), 'utf8')
    fs.writeFileSync(path.join(VENDOR_DIR, 'LICENSE.txt'), license)
    fs.writeFileSync(path.join(VENDOR_DIR, 'VENDORED.md'),
`# Vendored VS Code piece tree

Compiled output of the piece-tree text buffer from microsoft/vscode
(MIT licensed, see LICENSE.txt). Do not edit by hand — regenerate with:

    node script/update-vendored-piece-tree.js [--repo <path-or-url>] [--ref <ref>]

- Source: ${checkout.source}
- Commit: ${checkout.commit}
- Extracted: ${new Date().toISOString()}
- Files: ${SOURCE_FILES.join(', ')}
- Stubbed: ${Object.keys(STUB_FILES).join(', ')} (built-in search hooks; unused by superstring)
`)

    console.log('Smoke-testing the compiled output ...')
    smokeTest(VENDOR_DIR)
    console.log(`Vendored VS Code piece tree @ ${checkout.commit} into vendor/vscode-piecetree/`)
    console.log("Now run 'npm run test:node' — the adapter fuzz suite is the acceptance gate.")
  } finally {
    fs.rmSync(staging, {recursive: true, force: true})
    checkout.cleanup()
  }
}

main()
